def _save_tmp(fig, tmp_files: List[Path]) -> Path:
    fd, tmp_str = tempfile.mkstemp(suffix=".png")
    os.close(fd)
    tmp = Path(tmp_str)
    fig.savefig(tmp, dpi=170, bbox_inches="tight")
    plt.close(fig)
    tmp_files.append(tmp)
    return tmp


def render_experiment_a_figure(exp_a: Dict[str, Any], tmp_files: List[Path]) -> Path:
    per_class = exp_a["per_class"]
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.2))

    for i, (cls, data) in enumerate(sorted(per_class.items(), key=lambda kv: int(kv[0]))):
        color = CLASS_COLOR_CYCLE[i % len(CLASS_COLOR_CYCLE)]
        k = np.arange(1, len(data["r_curve"]) + 1)
        axes[0].plot(k, data["r_curve"], color=color, lw=1, alpha=0.85,
                     label=data["label"])
        axes[1].plot(k, data["gram_condition_number_curve"], color=color, lw=1, alpha=0.85)

    axes[0].set_title("Кривая R(k)", fontsize=9)
    axes[0].set_xlabel("Итерация k (порядок присоединения)", fontsize=8)
    axes[0].set_ylabel("R лучшего кандидата на шаге k", fontsize=8)
    axes[0].tick_params(labelsize=7)
    axes[0].grid(True, alpha=0.3)

    axes[1].set_title("Число обусловленности cond(Y^T Y)", fontsize=9)
    axes[1].set_xlabel("Итерация k", fontsize=8)
    axes[1].set_ylabel("cond(Y^T Y), лог. шкала", fontsize=8)
    axes[1].set_yscale("log")
    axes[1].tick_params(labelsize=7)
    axes[1].grid(True, alpha=0.3)

    axes[0].legend(fontsize=6, ncol=2, loc="upper right")
    fig.tight_layout()
    return _save_tmp(fig, tmp_files)


def render_experiment_c_figure(exp_c: Dict[str, Any], tmp_files: List[Path]) -> Path:
    fig, ax = plt.subplots(figsize=(6.2, 3.2))
    true_rank = exp_c["true_rank"]
    colors = ["#2563EB", "#16A34A", "#DC2626"]
    for i, entry in enumerate(exp_c["noise_levels"]):
        k = np.arange(1, len(entry["r_curve"]) + 1)
        ax.plot(k, entry["r_curve"], color=colors[i % len(colors)], lw=1.3,
                label=f"шум σ={entry['noise_std']}")
    ax.axvline(true_rank, color="grey", linestyle="--", lw=1,
                label=f"истинный ранг r={true_rank}")
    ax.set_xlabel("Итерация k", fontsize=8)
    ax.set_ylabel("R лучшего кандидата", fontsize=8)
    ax.set_title("Синтетика: кривая R(k) при известной истинной размерности", fontsize=9)
    ax.tick_params(labelsize=7)
    ax.legend(fontsize=7)
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    return _save_tmp(fig, tmp_files)


def render_experiment_b_figure(exp_b: Dict[str, Any], tmp_files: List[Path]) -> Path:
    configs = exp_b["configs"]
    labels = [CONFIG_LABEL_RU_SHORT.get(c["config_label"], c["config_label"]) for c in configs]
    times = [c["total_fit_time_seconds"] for c in configs]
    r_quality = [c["own_class_r_quality"] for c in configs]
    accuracy = [c["test_accuracy"] for c in configs]

    fig, ax1 = plt.subplots(figsize=(6.6, 3.2))
    x = np.arange(len(labels))
    ax1.bar(x, times, color="#94A3B8", width=0.5, label="время обучения, с")
    ax1.set_ylabel("Суммарное время обучения, с", fontsize=8)
    ax1.set_xticks(x)
    ax1.set_xticklabels(labels, rotation=25, ha="right", fontsize=6.5)
    ax1.tick_params(labelsize=7)

    ax2 = ax1.twinx()
    ax2.plot(x, r_quality, color="#DC2626", marker="o", lw=1.5, label="показатель качества R (свой класс)")
    ax2.plot(x, accuracy, color="#16A34A", marker="s", lw=1.5, label="точность классификации")
    ax2.set_ylabel("Показатель качества / точность", fontsize=7.5)
    ax2.tick_params(labelsize=7)
    ax2.set_ylim(0, 1.05)
