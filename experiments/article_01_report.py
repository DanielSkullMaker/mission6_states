def generate_report() -> None:
    with open(RESULTS_PATH, encoding="utf-8") as f:
        results = json.load(f)

    doc = Document()
    tmp_files: List[Path] = []
    configure_document_font(doc)

    add_title(doc)
    add_intro_section(doc)
    add_theory_section(doc, tmp_files)
    add_dataset_section(doc, results, tmp_files)
    add_heading(doc, "4. Результаты эксперимента", level=1)
    add_results_a_section(doc, results["experiment_a_convergence_curves"], tmp_files)
    add_results_b_section(doc, results["experiment_b_early_stopping"], tmp_files)
    add_results_c_section(doc, results["experiment_c_synthetic"], tmp_files)
    add_discussion_section(doc, results)
    add_conclusions_section(doc)
    add_future_work_section(doc)

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc.save(REPORT_PATH)

    for tmp in tmp_files:
        tmp.unlink(missing_ok=True)

    print(f"Отчёт сохранён: {REPORT_PATH}")


if __name__ == "__main__":
    generate_report()
