def render_accuracy_figure(test_results: Dict[str, Any], tmp_files: List[Path]) -> Path:
    names = [n for n in ALL_MODEL_ORDER if n in test_results]
    labels = [MODEL_LABEL_RU_SHORT.get(n, n) for n in names]
    acc = [test_results[n]["accuracy"] for n in names]
    colors = ["#94A3B8"] * len(BASELINE_ORDER) + ["#2563EB"] * (len(names) - len(BASELINE_ORDER))

    fig, ax = plt.subplots(figsize=(6.4, 3.0))
    bars = ax.bar(labels, acc, color=colors, width=0.55)
    for bar, v in zip(bars, acc):
        ax.text(bar.get_x() + bar.get_width() / 2, v + 0.012, f"{v:.3f}", ha="center", fontsize=7)
    ax.set_ylabel("Точность на тестовой выборке", fontsize=8)
    ax.set_ylim(0, min(1.05, max(acc) * 1.25))
    ax.tick_params(labelsize=7)
    ax.axvline(len(BASELINE_ORDER) - 0.5, color="#111827", linestyle=":", lw=1)
    ax.set_title("Одиночные представления (серые) и гибридизация (синие)", fontsize=9)
    fig.tight_layout()
    return _save_tmp(fig, tmp_files)


def render_per_class_figure(test_results: Dict[str, Any], class_labels: Dict[str, str], tmp_files: List[Path]) -> Path:
    names = [n for n in ALL_MODEL_ORDER if n in test_results]
    classes = list(next(iter(test_results.values()))["per_class_accuracy"].keys())
    x = np.arange(len(classes))
    width = 0.8 / len(names)

    fig, ax = plt.subplots(figsize=(6.6, 3.2))
    colors = plt.cm.tab10(np.linspace(0, 1, len(names)))
    for i, name in enumerate(names):
        vals = [test_results[name]["per_class_accuracy"][c] for c in classes]
        ax.bar(x + i * width, vals, width=width, label=MODEL_LABEL_RU_SHORT.get(name, name).replace("\n", " "),
               color=colors[i])
    ax.set_xticks(x + width * (len(names) - 1) / 2)
    ax.set_xticklabels([class_labels.get(c, c) for c in classes], fontsize=7.5)
    ax.set_ylabel("Точность внутри класса", fontsize=8)
    ax.set_ylim(0, 1.15)
    ax.legend(fontsize=6, ncol=3, loc="upper center")
    ax.set_title("Точность каждого варианта представления по классам", fontsize=9)
    fig.tight_layout()
    return _save_tmp(fig, tmp_files)


