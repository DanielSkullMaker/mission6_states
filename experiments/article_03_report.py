def add_tuning_section(doc: Document, results: Dict[str, Any]) -> None:
    add_heading(doc, "4. Подбор гиперпараметров", level=1)
    tuning = results.get("tuning")
    if not tuning:
        add_p(
            doc,
            "Этот прогон не включает подбор гиперпараметров — использованы "
            "значения по умолчанию."
        )
        return

    add_p(
        doc,
        f"Раздел 2.3 доказывает, что направление развёртки не может "
        f"повлиять на решение метода, — но ничего не говорит об АБСОЛЮТНОМ "
        f"уровне точности: он целиком определяется гиперпараметрами "
        f"самого базового метода (числом подпространств на класс и "
        f"правилом их роста), одинаковыми для всех шести вариантов. Чтобы "
        f"добросовестно поднять точность, эти гиперпараметры подбираются "
        f"на отдельной проверочной выборке, carved из обучающей — "
        f"{tuning['search_n_per_class']} изображений на класс на "
        f"промежуточное обучение и ещё {tuning['search_n_per_class']} на "
        f"проверку (тестовая выборка, раздел 3, в подборе не участвует "
        f"вообще). Подбор идёт ТОЛЬКО на горизонтальном представлении — "
        f"теорема раздела 2.3 гарантирует, что при любых фиксированных "
        f"гиперпараметрах вертикальное представление и все способы "
        f"объединения дадут тот же результат, так что подбирать для "
        f"каждого из шести вариантов отдельно было бы шестикратной тратой "
        f"времени без единого шанса получить другой ответ."
    )

    add_heading(doc, "4.1. Найденная и исправленная ошибка первой попытки подбора", level=2)
    add_p(
        doc,
        "Первая попытка подбора использовала проверочную выборку всего "
        "40 изображений на класс и перебирала 26 конфигураций — "
        "победила конфигурация с точностью 0.825 на этой проверочной "
        "выборке (заметно выше, чем у настроек по умолчанию, "
        "показавших 0.742). На НЕЗАВИСИМОМ тесте эта \"победившая\" "
        "конфигурация дала точность 0.3417 — ХУЖЕ первоначальных 0.4417, "
        "полученных вообще без всякого подбора. Причина — классический "
        "оверфиттинг к шуму маленькой проверочной выборки: при переборе "
        "26 конфигураций почти гарантированно находится конфигурация, "
        "которая случайно хорошо легла именно на эти 120 проверочных "
        "изображений (40 на класс), но не обобщается на новые. Ошибка "
        "была обнаружена именно честной проверкой на отложенном тесте "
        "(она для того и существует) и исправлена увеличением "
        "проверочной выборки вдвое относительно самого теста и сужением "
        "перебираемой сетки — результаты ниже относятся уже к "
        "исправленной, второй попытке."
    )

    add_heading(doc, "4.2. Опробованные конфигурации", level=2)
    candidates = tuning["candidates"]
    best = tuning["best_config"]
    headers = ["Фаза", "n_subclasses", "growth_strategy", "filter_dependent",
               "split_correlated_pairs", "Точность на проверочной выборке"]
    rows = []
    bold_idx = []
    for i, c in enumerate(candidates):
        split_label = (
            f"да ({c['correlated_pairs_subset']})" if c["split_correlated_pairs"] else "нет"
        )
        rows.append([
            str(c["phase"]), str(c["n_subclasses"]), c["growth_strategy"],
            "да" if c["filter_dependent"] else "нет", split_label,
            f"{c['val_accuracy']:.4f}" if c["val_accuracy"] > float("-inf") else "конфигурация невалидна",
        ])
        if (
            c["n_subclasses"] == best["n_subclasses"]
            and c["growth_strategy"] == best["growth_strategy"]
            and c["filter_dependent"] == best["filter_dependent"]
            and c["split_correlated_pairs"] == best["split_correlated_pairs"]
            and c.get("correlated_pairs_subset") == best.get("correlated_pairs_subset")
        ):
            bold_idx.append(i)
    add_table_9pt(doc, headers, rows, bold_row_indices=bold_idx)
    add_p(
        doc,
        f"Победила конфигурация n_subclasses={best['n_subclasses']}, "
        f"growth_strategy=\"{best['growth_strategy']}\" (без дополнительных "
        f"фильтров) — точность на проверочной выборке "
        f"{best['val_accuracy']:.4f}. Значения точности по сетке заметно "
        f"немонотонны (например, точность у соседних значений n_subclasses "
        f"может отличаться в разы) — это, по всей видимости, отражает "
        f"собственную неустойчивость жадного алгоритма роста подпространств "
        f"(раздел 3) к небольшим изменениям числа подклассов, а не только "
        f"шум проверочной выборки: конкретный подкласс, которому по "
        f"случайному стечению обстоятельств достаётся большинство "
        f"эталонных векторов класса, — и, соответственно, качество "
        f"итоговой классификации — может резко меняться от одной "
        f"конфигурации к соседней."
    )
    doc.add_page_break()


def add_results_section(doc: Document, results: Dict[str, Any], tmp_files: List[Path]) -> None:
    add_heading(doc, "5. Результаты эксперимента", level=1)
    test_results = results["test_results"]
    config = results["config"]
    labels = config["class_labels_ru"]

    all_names = [n for n in ALL_MODEL_ORDER if n in test_results]
    accs = [test_results[n]["accuracy"] for n in all_names]
    exact_match = (max(accs) - min(accs)) < 1e-9
    classes = list(next(iter(test_results.values()))["per_class_accuracy"].keys())
    per_class_exact_match = all(
        max(test_results[n]["per_class_accuracy"][c] for n in all_names)
        - min(test_results[n]["per_class_accuracy"][c] for n in all_names) < 1e-9
        for c in classes
    )

    add_heading(doc, "5.1. Общая точность шести вариантов", level=2)
    add_p(
        doc,
        "Первые два варианта — «одиночные» представления (то, что "
        "использовалось в проекте до этой статьи, и то, что было посчитано, "
        "но не использовалось ни разу); остальные четыре — разные способы "
        "их объединения (раздел 2.4)."
    )
    add_p(
        doc,
        (
            f"Предсказание раздела 2.3 подтвердилось буквально: все шесть "
            f"вариантов дали ОДНУ И ТУ ЖЕ точность на тестовой выборке — "
            f"{accs[0]:.4f} — совпадающую вплоть до знаков, которые выводит "
            f"компьютер. Это не «примерно одинаковый», а поразрядно "
            f"идентичный результат: горизонтальная, вертикальная модели, "
            f"конкатенация и все три способа их объединения на каждом "
            f"тестовом изображении принимают ОДНО И ТО ЖЕ решение."
            if exact_match else
            f"Вопреки предсказанию раздела 2.3, точность вариантов разошлась "
            f"(от {min(accs):.4f} до {max(accs):.4f}) — см. обсуждение "
            f"(раздел 5) о том, что могло нарушить условия теоретического "
            f"вывода."
        )
    )
    acc_chart = render_accuracy_figure(test_results, tmp_files)
    add_picture_centered(doc, acc_chart, width_in=6.0)
    add_caption(doc, "Рис. 3. Точность на тестовой выборке — все шесть вариантов представления.")

    headers = ["Вариант", "Точность", "Средняя по классам"]
    rows = [
        [MODEL_LABEL_RU[n], f"{test_results[n]['accuracy']:.4f}", f"{test_results[n]['macro_accuracy']:.4f}"]
        for n in ALL_MODEL_ORDER if n in test_results
    ]
    best_acc = max(test_results[n]["accuracy"] for n in ALL_MODEL_ORDER if n in test_results)
    bold_idx = [i for i, n in enumerate(ALL_MODEL_ORDER) if n in test_results and abs(test_results[n]["accuracy"] - best_acc) < 1e-9]
    add_table_9pt(doc, headers, rows, bold_row_indices=bold_idx)

    add_heading(doc, "5.2. Точность по классам патологий", level=2)
    add_p(
        doc,
        "Задача 3 (раздел 1) требовала проверить предсказание раздела 2.3 "
        "не только «в среднем», но и отдельно по каждому классу патологий "
        "— теоретическое утверждение о ТОЖДЕСТВЕННОСТИ решений обязано "
        "выполняться без единого исключения."
    )
    per_class_chart = render_per_class_figure(test_results, labels, tmp_files)
    add_picture_centered(doc, per_class_chart, width_in=6.2)
    add_caption(
        doc,
        "Рис. 4. Точность каждого варианта представления внутри каждого "
        "класса — шесть столбцов каждой группы совпадают настолько точно, "
        "что визуально сливаются в один."
    )

    headers = ["Вариант"] + [labels.get(c, c) for c in classes]
    rows = [
        [MODEL_LABEL_RU_SHORT[n].replace("\n", " ")] +
        [f"{test_results[n]['per_class_accuracy'][c]:.3f}" for c in classes]
        for n in ALL_MODEL_ORDER if n in test_results
    ]
    add_table_9pt(doc, headers, rows)
    add_p(
        doc,
        (
            "Совпадение точное и по каждому классу в отдельности, без "
            "исключений — ровно то, что предсказывает теорема раздела 2.3: "
            "она утверждает тождество решений для КАЖДОГО объекта "
            "по отдельности, а значит и для любой его группы, включая "
            "разбиение по классам."
            if per_class_exact_match else
            "Точность разошлась хотя бы для одного класса — см. обсуждение "
            "(раздел 5)."
        )
    )

    add_heading(doc, "5.3. Время обучения и предсказания", level=2)
